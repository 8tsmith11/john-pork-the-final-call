#!/usr/bin/env python3
"""Seal or unseal the romance dialogue (D-014).

The scenes ship as ROT13-encoded JSON in src/content/dialogue/act1/romance_*.js, the same format
tools/dialogue/convert.py writes, so the source doesn't spoil anyone browsing the repo.

  python3 tools/romance/seal.py decode romance_trevor > /tmp/romance_trevor.json   # edit this
  python3 tools/romance/seal.py encode /tmp/romance_trevor.json                    # writes the .js

Scene JSON: {"scene", "start", "order", "nodes": {id: {"lines": [{"who", "text", "if"}],
"choices": [{"text", "go", "if"}], "go", "effects": [{"op": "set", "arg": "flag = value", "if"}]}}}
"""
import codecs
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "src" / "content" / "dialogue" / "act1"
HEADER = ("// GENERATED by tools/romance/seal.py (romance, D-014). Edit with its decode/encode commands.\n"
          "// ROT13-encoded so the source doesn't spoil the story; decoded by src/engine/dialogue.js.\n")


def encode(path):
    scene = json.loads(Path(path).read_text())
    for nid, node in scene["nodes"].items():
        node.setdefault("lines", []); node.setdefault("choices", []); node.setdefault("go", None); node.setdefault("effects", [])
        for ln in node["lines"]:
            ln.setdefault("if", None)
            if ln.get("who") is None:
                ln["narr"] = True
        for c in node["choices"]:
            c.setdefault("if", None)
            assert c["go"] in scene["nodes"], f"{nid}: choice goes to missing node {c['go']}"
        for e in node["effects"]:
            e.setdefault("if", None)
        assert node["go"] is None or node["go"] in scene["nodes"], f"{nid}: go to missing node {node['go']}"
    scene.setdefault("order", list(scene["nodes"]))
    body = codecs.encode(json.dumps(scene, ensure_ascii=False, separators=(",", ":")), "rot13")
    out = OUT / f"{scene['scene']}.js"
    out.write_text(HEADER + "export default " + json.dumps(body, ensure_ascii=False) + ";\n")
    print(f"sealed {out.relative_to(REPO)} ({len(scene['nodes'])} nodes)")


def decode(name):
    src = (OUT / f"{name}.js").read_text()
    body = json.loads(re.search(r"export default\s*(\".*\")", src, re.S).group(1))
    print(json.dumps(json.loads(codecs.decode(body, "rot13")), ensure_ascii=False, indent=1))


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] not in ("encode", "decode"):
        sys.exit(__doc__)
    (encode if sys.argv[1] == "encode" else decode)(sys.argv[2])
