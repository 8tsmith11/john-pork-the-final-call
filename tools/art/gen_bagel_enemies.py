#!/usr/bin/env python3
"""Enemy sprites for the D-017 coderot (16x16, two frames each): assets/src/bagel_enemies.txt.

Frame names are `<enemy kind>_<n>` like the main enemies sheet, so BootScene can make the walk anims.
Run this, then `python3 tools/art/build.py bagel_enemies`.
"""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PAL = [k for k in json.loads((REPO / "tools/art/palette.json").read_text()) if not k.startswith("_")]
LETTERS = "0123abcdefghijklmnopqrstuvwxyzABCDEF"
L = dict(zip(PAL, LETTERS))


class C:
    def __init__(self):
        self.g = [["."] * 16 for _ in range(16)]

    def px(self, x, y, c):
        if 0 <= x < 16 and 0 <= y < 16: self.g[y][x] = L[c]
        return self

    def rect(self, x, y, w, h, c):
        for yy in range(y, y + h):
            for xx in range(x, x + w): self.px(xx, yy, c)
        return self

    def pts(self, c, *ps):
        for x, y in ps: self.px(x, y, c)
        return self

    def outline(self, c="night0"):
        src = [r[:] for r in self.g]
        for y in range(16):
            for x in range(16):
                if src[y][x] == "." and any(0 <= x + dx < 16 and 0 <= y + dy < 16 and src[y + dy][x + dx] != "." for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    self.g[y][x] = L[c]
        return self

    def rows(self): return ["".join(r) for r in self.g]


def moth(f):
    """Hold-Music Moth: pale wings that beat, a speaker-grille body, a little note above it."""
    c = C()
    up = 1 if f else 0
    c.rect(2, 4 - up, 5, 5, "bone").rect(9, 4 - up, 5, 5, "bone").rect(3, 5 - up, 3, 3, "concrete3").rect(10, 5 - up, 3, 3, "concrete3")
    c.rect(6, 4, 4, 9, "night3").pts("steel", (7, 6), (8, 6), (7, 8), (8, 8), (7, 10), (8, 10))     # speaker grille
    c.pts("rot0", (7, 3), (8, 3)).pts("screen2", (6, 5), (9, 5))                                      # antennae, eyes
    c.pts("pork2", (12 + f, 1), (12 + f, 2), (13 + f, 1))                                              # a floating note
    return c.outline()


def captcha(f):
    """Captcha: a 3x3 grid of checkboxes on stubby legs, one box always ticked."""
    c = C()
    c.rect(2, 2, 12, 11, "concrete2")
    for gx in range(3):
        for gy in range(3):
            c.rect(3 + gx * 4, 3 + gy * 3, 2, 2, "bone")
    c.pts("yerba1", (7, 6), (8, 7)).pts("signal", (11, 9 - f))                                         # a tick, a red light
    c.rect(4, 13, 2, 2 + f, "night2").rect(10, 13, 2, 3 - f, "night2")
    return c.outline()


def autocomplete(f):
    """Autocomplete: a lean cyan cursor-shaped thing, trailing ghost copies of itself."""
    c = C()
    o = 1 if f else 0
    c.pts("screen0", *[(2 + o + i, 4 + i) for i in range(6)])                                         # the ghost copy
    for i in range(8): c.rect(6 + o, 2 + i, 1 + i // 2, 1, "screen2")                                  # the cursor arrow
    c.rect(8 + o, 9, 2, 5, "screen1").pts("bone", (7 + o, 4))
    return c.outline()


FRAMES = {}
for name, fn in (("enemy.moth", moth), ("enemy.captcha", captcha), ("enemy.autocomplete", autocomplete)):
    for f in (0, 1):
        FRAMES[f"{name}_{f}"] = fn(f).rows()

out = ["# bagel_enemies: generated by tools/art/gen_bagel_enemies.py. Do not hand-edit; change the generator.",
       "@size 16 16", "@map " + " ".join(f"{L[k]}={k}" for k in PAL)]
for n, rows in FRAMES.items():
    out.append(f"@frame {n}")
    out.extend(rows)
(REPO / "assets" / "src" / "bagel_enemies.txt").write_text("\n".join(out) + "\n")
print(f"bagel_enemies: {len(FRAMES)} frames")
